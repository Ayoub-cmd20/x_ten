String wilayaLabel(BuildContext context, String code) {
  final wilaya = wilayas.where((w) => w.code == code).firstOrNull;
  if (wilaya == null) {
    return code;
  }
  final arabic = Localizations.localeOf(context).languageCode == 'ar';
  return '${wilaya.code} - ${arabic ? wilaya.arabic : wilaya.latin}';
}
